export const HOLDER_ENTITY_BY_OWNER = new Map(HOLDER_ENTITIES.map(entity => [entity.owner, entity]));
export function isPooledCustody(owner: string) {
  const entity = HOLDER_ENTITY_BY_OWNER.get(owner);
  return !!entity && entity.category !== "trading firm";
}
export const HOLDER_POOLED_KEY = HOLDER_ENTITIES.filter(entity => isPooledCustody(entity.owner)).map(entity => entity.owner).sort().join(",");

/** Filter before limiting and keep ranks relative to the entire selected tracked view. */
export function holderView<T extends { owner: string; rank: number }>(entries: T[], excludePooled: boolean) {
  return entries.filter(entry => !excludePooled || !isPooledCustody(entry.owner))
    .map((entry, index) => ({ ...entry, viewRank: excludePooled ? index + 1 : entry.rank }));
}
